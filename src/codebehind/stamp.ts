/**
 * The version stamp a compiled steps file carries (docs/specs/SPEC-install.md
 * §4.13): one comment line in the file's opening comments, such as
 *
 *     // Compiled by Steptix 1.5.2.
 *
 * once for the whole file, never per step. A compile writes it with its own
 * version; a reader of an older major.minor leaves the file alone and runs its
 * steps with the AI (loader.ts). The rule itself is src/utils/file-stamp.ts.
 */

import path from 'node:path';
import { majorMinorLabel } from '../utils/file-stamp.js';
import { getPackageVersion } from '../utils/version.js';

const STAMP_LINE = /^\/\/ Compiled by Steptix (\S+?)\.?[ \t]*$/;

/** The opening run of `//` comment lines, where the stamp lives. */
function headerLength(lines: string[]): number {
  let n = 0;
  while (n < lines.length && /^\s*\/\//.test(lines[n]!)) n++;
  return n;
}

/** The version the file says compiled it, or undefined for a file with none. */
export function codeBehindStamp(text: string): string | undefined {
  const lines = text.split(/\r?\n/);
  const header = headerLength(lines);
  for (let i = 0; i < header; i++) {
    const m = STAMP_LINE.exec(lines[i]!);
    if (m) return m[1];
  }
  return undefined;
}

/**
 * `text` stamped as compiled by `version`: an existing stamp is replaced, and
 * a file without one gets it after its first comment line (the "Generated by
 * Steptix" line a compiled file starts with), or at the top.
 */
export function withCodeBehindStamp(text: string, version: string): string {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const lines = text.split(/\r?\n/);
  const stamp = `// Compiled by Steptix ${version}.`;
  const header = headerLength(lines);
  for (let i = 0; i < header; i++) {
    if (STAMP_LINE.test(lines[i]!)) {
      lines[i] = stamp;
      return lines.join(eol);
    }
  }
  lines.splice(header > 0 ? 1 : 0, 0, stamp);
  return lines.join(eol);
}

/** The two ways out a client names (§4.13): how to update, and how to
 *  recompile with this version. Each is a clause the notice joins with ", or". */
export interface UpdateWords {
  update: string;
  recompile: string;
}

/** What `steptix run` in a terminal says. `testFile` is shown as given. */
export function terminalUpdateWords(testFile: string): UpdateWords {
  return {
    update: 'Update with npm i -g steptix to use them',
    recompile: `recompile them with this version: steptix compile ${testFile}`,
  };
}

/** What the server says to a client it knows nothing about. VS Code puts its
 *  own words in their place (the output event's `newerCompiled`). */
export const SERVER_UPDATE_WORDS: UpdateWords = {
  update: 'Update Steptix to use them',
  recompile: 'recompile them with this version',
};

/**
 * The run's notice about a compiled steps file a newer major.minor wrote:
 * "3 steps were compiled by Steptix 1.5 and ran with the AI instead. Update
 * with npm i -g steptix to use them, or recompile them with this version:
 * steptix compile tests/login.md."
 */
export function newerCompiledNotice(
  newer: { file: string; version: string; steps: number },
  words: UpdateWords,
  own: string = getPackageVersion(),
): string {
  const by = `Steptix ${majorMinorLabel(newer.version)}`;
  const what =
    newer.steps > 0
      ? `${newer.steps} step${newer.steps === 1 ? ' was' : 's were'} compiled by ${by} and ran with the AI instead.`
      : `The compiled steps in ${path.basename(newer.file)} were written by ${by} and are not used by this ${majorMinorLabel(own)}.`;
  return `${what} ${words.update}, or ${words.recompile}.`;
}

/** Added to the failure of a step whose compiled entry a newer major.minor
 *  wrote, on a run with no AI to run it with instead (§4.13). */
export function newerCompiledStepNote(version: string, own: string = getPackageVersion()): string {
  return (
    `This step was compiled by Steptix ${majorMinorLabel(version)}, and this ${majorMinorLabel(own)} ` +
    'does not run steps a newer version compiled: update Steptix to run it as code.'
  );
}
