/**
 * Files say which version wrote them (docs/specs/SPEC-install.md §4.13): the
 * stamp each file Steptix writes in a project to read back carries, and what
 * a reader of an older major.minor does with a newer one: leaves it unused,
 * never rewrites it on its own, and says so.
 *
 * This build's own version is the repo's package.json version, so "newer"
 * here is 99.0.0 and "older" is 0.1.0.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { majorMinorLabel, writtenByNewer, STAMP_FIELD } from '../src/utils/file-stamp.js';
import { getPackageVersion } from '../src/utils/version.js';
import {
  codeBehindStamp,
  newerCompiledNotice,
  newerCompiledStepNote,
  terminalUpdateWords,
  withCodeBehindStamp,
} from '../src/codebehind/stamp.js';
import { buildCodeBehindRegistry, codeBehindPathFor } from '../src/codebehind/loader.js';
import { Candidate } from '../src/codebehind/candidate.js';
import { lastRunPathFor, readLastRun, writeLastRun } from '../src/codebehind/last-run.js';
import { recordingDirFor, spliceRecording } from '../src/codebehind/recording.js';
import { readProfileMarker } from '../src/browser/cdp-registry.js';
import { parseTestFile } from '../src/parser/markdown.js';
import { clearSkillCache } from '../src/skills/expander.js';
// runner-core's source, as control-line-parity.test.ts explains.
import { newerCompiledText, outputText } from '../runner-core/src/newer-compiled.ts';
import { makeScratchBase, removeScratchBase } from './codebehind-scratch.js';

const OWN = getPackageVersion();

describe('comparing versions', () => {
  it('counts only a newer major.minor as newer', () => {
    expect(writtenByNewer('1.5.2', '1.4.9')).toBe(true);
    expect(writtenByNewer('2.0.0', '1.9.3')).toBe(true);
    expect(writtenByNewer('1.10.0', '1.9.0')).toBe(true);
    // Patches never change a file's format (§4.2).
    expect(writtenByNewer('1.4.9', '1.4.0')).toBe(false);
    expect(writtenByNewer('1.4.0', '1.5.0')).toBe(false);
    expect(writtenByNewer('1.5.0-beta.1', '1.4.0')).toBe(true);
  });

  it('reads a file with no stamp, or one it cannot compare, as it always did', () => {
    expect(writtenByNewer(undefined, '1.0.0')).toBe(false);
    expect(writtenByNewer('not a version', '1.0.0')).toBe(false);
    expect(writtenByNewer('9.0.0', 'unknown')).toBe(false);
    expect(majorMinorLabel('1.5.2')).toBe('1.5');
  });
});

describe('the compiled steps stamp', () => {
  const file = [
    '// Generated by Steptix — code-behind for login.md.',
    '// Safe to hand-edit: entries match steps by their `source` text.',
    "import { defineSteps } from 'steptix/codebehind';",
    '',
  ].join('\n');

  it('goes once at the top, after the first comment line, and is replaced, never repeated', () => {
    const stamped = withCodeBehindStamp(file, '1.5.2');
    expect(stamped.split('\n').slice(0, 2)).toEqual([
      '// Generated by Steptix — code-behind for login.md.',
      '// Compiled by Steptix 1.5.2.',
    ]);
    expect(codeBehindStamp(stamped)).toBe('1.5.2');
    const again = withCodeBehindStamp(stamped, '1.6.0');
    expect(codeBehindStamp(again)).toBe('1.6.0');
    expect(again.match(/Compiled by Steptix/g)).toHaveLength(1);
  });

  it('is read only from the opening comments, and a file without them gets it at the top', () => {
    expect(codeBehindStamp(file)).toBeUndefined();
    expect(codeBehindStamp(`${file}// Compiled by Steptix 9.0.0.\n`)).toBeUndefined();
    expect(withCodeBehindStamp("import x from 'y';\n", '1.0.0')).toBe("// Compiled by Steptix 1.0.0.\nimport x from 'y';\n");
    expect(withCodeBehindStamp('// a\r\n// b\r\nx\r\n', '1.0.0')).toBe('// a\r\n// Compiled by Steptix 1.0.0.\r\n// b\r\nx\r\n');
  });

  it('is on the sample project the install ships', async () => {
    const sample = await fs.readFile(path.resolve('templates/sample/tests/first-test.steps.ts'), 'utf8');
    expect(codeBehindStamp(sample)).toBe(OWN);
  });
});

describe('what the run says', () => {
  it('names the steps, the version and both ways out, in the terminal and in VS Code', () => {
    const newer = { file: path.resolve(path.sep, 'p', 'tests', 'login.steps.ts'), version: '1.5.2', steps: 3 };
    expect(newerCompiledNotice(newer, terminalUpdateWords('tests/login.md'))).toBe(
      '3 steps were compiled by Steptix 1.5 and ran with the AI instead. Update with npm i -g steptix ' +
        'to use them, or recompile them with this version: steptix compile tests/login.md.',
    );
    expect(newerCompiledText(newer)).toBe(
      '3 steps were compiled by Steptix 1.5 and ran with the AI instead. Update the Steptix extension ' +
        'to use them, or recompile them with this version: Steptix: Compile Code-behind.',
    );
    expect(outputText({ msg: 'the server words', newerCompiled: newer })).toBe(newerCompiledText(newer));
    expect(outputText({ msg: 'anything else' })).toBe('anything else');
    expect(newerCompiledNotice({ ...newer, steps: 1 }, terminalUpdateWords('t.md'))).toMatch(/^1 step was compiled/);
    expect(newerCompiledStepNote('1.5.2', '1.4.0')).toBe(
      'This step was compiled by Steptix 1.5, and this 1.4 does not run steps a newer version compiled: ' +
        'update Steptix to run it as code.',
    );
  });
});

describe('reading files a newer version wrote', () => {
  let base: string;
  let dir: string;
  let n = 0;
  beforeAll(async () => {
    base = await makeScratchBase('file-stamps');
  });
  afterAll(async () => {
    await removeScratchBase(base);
  });
  beforeEach(async () => {
    clearSkillCache();
    dir = path.join(base, `t${n++}`);
    await fs.mkdir(dir, { recursive: true });
  });

  /** A test of two steps, with a compiled steps file stamped `stamp`. */
  async function compiledTest(stamp: string | null): Promise<string> {
    const test = path.join(dir, 'login.md');
    await fs.writeFile(test, '# Login\n\n## Steps\n1. Open the page\n2. Click Save\n', 'utf8');
    const entries = ['Open the page', 'Click Save']
      .map((source) => `  { source: ${JSON.stringify(source)}, async run() {} },`)
      .join('\n');
    await fs.writeFile(
      codeBehindPathFor(test),
      `// Generated by Steptix — code-behind for login.md.\n${stamp === null ? '' : `// Compiled by Steptix ${stamp}.\n`}` +
        `import { defineSteps } from 'steptix/codebehind';\nexport default defineSteps([\n${entries}\n]);\n`,
      'utf8',
    );
    return test;
  }

  async function registryFor(test: string, warnings: string[]) {
    const parsed = await parseTestFile(test, {});
    const expansion = parsed.expansion!;
    return buildCodeBehindRegistry(
      { steps: parsed.steps, rawSteps: expansion.rawSteps, origins: expansion.origins, frames: expansion.frames },
      { testFilePath: parsed.filePath, onWarn: (m) => warnings.push(m) },
    );
  }

  it('runs no compiled step a newer major.minor wrote, and counts the ones it would have', async () => {
    const test = await compiledTest('99.0.0');
    const before = await fs.readFile(codeBehindPathFor(test), 'utf8');
    const warnings: string[] = [];
    const registry = await registryFor(test, warnings);
    for (const i of [0, 1]) {
      expect(registry.bindingFor(i)?.entry).toBeUndefined();
      expect(registry.bindingFor(i)?.newerStamp).toBe('99.0.0');
    }
    expect(registry.newerFiles).toEqual([{ file: codeBehindPathFor(test), version: '99.0.0', steps: 2 }]);
    expect(registry.loadErrors).toEqual([]);
    expect(warnings).toEqual([]);
    expect(await fs.readFile(codeBehindPathFor(test), 'utf8')).toBe(before);
  });

  it('runs what an older or unstamped file holds, as before', async () => {
    for (const stamp of ['0.1.0', OWN, null]) {
      const test = await compiledTest(stamp);
      const registry = await registryFor(test, []);
      expect(registry.bindingFor(0)?.entry?.source).toBe('Open the page');
      expect(registry.bindingFor(0)?.newerStamp).toBeUndefined();
      expect(registry.newerFiles).toEqual([]);
    }
  });

  it('compiles over a newer file from scratch, and stamps what it proposes with this version', async () => {
    const test = await compiledTest('99.0.0');
    const candidate = new Candidate();
    expect(await candidate.read(codeBehindPathFor(test))).toBeNull();
    expect([...candidate.replacedNewer()]).toEqual([[codeBehindPathFor(test), '99.0.0']]);
    await candidate.replaceFile(codeBehindPathFor(test), "import { defineSteps } from 'steptix/codebehind';\nexport default defineSteps([]);\n");
    expect(codeBehindStamp(candidate.contentOf(codeBehindPathFor(test))!)).toBe(OWN);
  });

  it("leaves a newer version's last-run file as it is, and stamps its own", async () => {
    const test = path.join(dir, 'login.md');
    const sidecar = lastRunPathFor(test);
    await fs.mkdir(path.dirname(sidecar), { recursive: true });
    const newer = `${JSON.stringify({ [STAMP_FIELD]: '99.0.0', test, ranAt: 'then', steps: [] })}\n`;
    await fs.writeFile(sidecar, newer, 'utf8');
    expect(await readLastRun(test)).toBeNull();
    await writeLastRun(test, [{ index: 1, source: 'Open the page', status: 'passed', fromCodeBehind: false, stale: false }]);
    expect(await fs.readFile(sidecar, 'utf8')).toBe(newer);

    await fs.rm(sidecar);
    await writeLastRun(test, [{ index: 1, source: 'Open the page', status: 'passed', fromCodeBehind: false, stale: false }]);
    const written = JSON.parse(await fs.readFile(sidecar, 'utf8')) as Record<string, unknown>;
    expect(written[STAMP_FIELD]).toBe(OWN);
    expect((await readLastRun(test))?.steps).toHaveLength(1);
  });

  it("starts a recording of its own rather than splicing into a newer version's", async () => {
    const test = path.join(dir, 'login.md');
    const recording = recordingDirFor(test);
    await fs.mkdir(recording, { recursive: true });
    await fs.writeFile(
      path.join(recording, 'recording.json'),
      JSON.stringify({ [STAMP_FIELD]: '99.0.0', test, startedAt: 'then', finishedAt: 'then', status: 'passed', steps: 1, parameters: ['newer'], source: 'cli' }),
      'utf8',
    );
    await fs.writeFile(path.join(recording, 'step-01.json'), '{"index":1,"instruction":"Open the page"}', 'utf8');
    await spliceRecording(test, { steps: [], status: 'passed', startedAt: 'now', parameters: {}, source: 'cli' });
    const manifest = JSON.parse(await fs.readFile(path.join(recording, 'recording.json'), 'utf8')) as Record<string, unknown>;
    expect(manifest[STAMP_FIELD]).toBe(OWN);
    expect(manifest['parameters']).toEqual([]);
    expect(await fs.readdir(recording)).toEqual(['recording.json']);
  });

  it("makes no claim from a newer version's browser profile marker", () => {
    const marker = (stamp: string) => ({
      readFileSync: () => JSON.stringify({ [STAMP_FIELD]: stamp, engine: 'chrome', profile: 'default', createdBy: 'steptix', hideAutomation: true }),
    });
    expect(readProfileMarker(dir, marker('99.0.0') as never)).toEqual({ hideAutomation: null });
    expect(readProfileMarker(dir, marker(OWN) as never)).toEqual({ hideAutomation: true });
  });
});
